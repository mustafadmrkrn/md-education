create schema if not exists ozel;
grant usage on schema ozel to authenticated, anon;

create table public.profiles(user_id uuid primary key references auth.users(id) on delete cascade, rol text not null check (rol in ('admin','kurum','ogretmen','ogrenci','veli')), ad text not null, eposta text);
create table public.kurumlar(ad text primary key, data jsonb not null default '{}');
create table public.hocalar(ad text primary key, data jsonb not null default '{}');
create table public.veliler(ad text primary key, data jsonb not null default '{}');
create table public.ogrenciler(ad text primary key, sinif text not null default '—', dersler text[] not null default '{}', aktif boolean not null default true);
create table public.ogrenci_ozel(ad text primary key, veli text, data jsonb not null default '{}');
create table public.dersler(id text primary key, hoca text not null default '', sira int not null default 0, data jsonb not null);
create table public.ders_ic(ders text primary key, gunluk jsonb not null default '[]');
create table public.yoklama(ders text, hafta int, ogrenci text, durum text check (durum in ('var','gec','erken','mazeret','yok')), neden text, metin text, primary key(ders,hafta,ogrenci));
create table public.ders_notu(ders text, hafta int, metin text, primary key(ders,hafta));
create table public.odevler(id bigint primary key, ders text not null, hedef text[], data jsonb not null);
create table public.teslimler(odev bigint, ogrenci text, data jsonb not null, primary key(odev,ogrenci));
create table public.degerlendirmeler(odev bigint, ogrenci text, data jsonb not null, primary key(odev,ogrenci));
create table public.kayitlar(ders text, hafta int, data jsonb not null, primary key(ders,hafta));
create table public.riza(ogrenci text primary key, data jsonb not null);
create table public.odemeler(id bigint primary key, ogrenci text not null, data jsonb not null);
create table public.basvuru(id bigint generated by default as identity primary key, data jsonb not null check (pg_column_size(data) < 2000), olusturma timestamptz not null default now());

-- kimlik yardımcıları (RLS'i dolanmadan, API'ye kapalı şemada)
create function ozel.rol() returns text language sql stable security definer set search_path='' as $$
  select p.rol from public.profiles p where p.user_id=(select auth.uid())
  and not exists(select 1 from public.hocalar h where p.rol='ogretmen' and h.ad=p.ad and h.data->>'aktif'='false')
  and not exists(select 1 from public.veliler v where p.rol='veli' and v.ad=p.ad and v.data->>'aktif'='false')
  and not exists(select 1 from public.ogrenciler o where p.rol='ogrenci' and o.ad=p.ad and not o.aktif)
$$;
create function ozel.ad() returns text language sql stable security definer set search_path='' as $$ select p.ad from public.profiles p where p.user_id=(select auth.uid()) and ozel.rol() is not null $$;
create function ozel.yonetici() returns boolean language sql stable security definer set search_path='' as $$ select coalesce(ozel.rol() in ('admin','kurum'),false) $$;
create function ozel.admin() returns boolean language sql stable security definer set search_path='' as $$ select coalesce(ozel.rol()='admin',false) $$;
-- öğrencinin kendisi veya velinin çocukları
create function ozel.cocuklar() returns setof text language sql stable security definer set search_path='' as $$
  select ozel.ad() where ozel.rol()='ogrenci'
  union select z.ad from public.ogrenci_ozel z where ozel.rol()='veli' and z.veli=ozel.ad()
$$;
create function ozel.hoca_dersi(d text) returns boolean language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.dersler x where x.id=d and ozel.rol()='ogretmen' and x.hoca=ozel.ad()) $$;
create function ozel.uye_dersi(d text) returns boolean language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.ogrenciler o where o.ad in (select ozel.cocuklar()) and d = any(o.dersler)) $$;
create function ozel.hoca_ogrencisi(a text) returns boolean language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.ogrenciler o join public.dersler x on x.id=any(o.dersler) where o.ad=a and ozel.rol()='ogretmen' and x.hoca=ozel.ad()) $$;
create function ozel.odev_dersi(i bigint) returns text language sql stable security definer set search_path='' as $$ select o.ders from public.odevler o where o.id=i $$;
create function ozel.odev_hedefi(i bigint, a text) returns boolean language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.odevler h join public.ogrenciler o on h.ders=any(o.dersler) where h.id=i and o.ad=a and (h.hedef is null or a=any(h.hedef))) $$;
grant execute on all functions in schema ozel to authenticated;

do $$ declare t text; begin
  foreach t in array array['profiles','kurumlar','hocalar','veliler','ogrenciler','ogrenci_ozel','dersler','ders_ic','yoklama','ders_notu','odevler','teslimler','degerlendirmeler','kayitlar','riza','odemeler','basvuru'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('revoke truncate, references, trigger on public.%I from authenticated', t);
  end loop; end $$;
grant select on public.dersler to anon;
grant insert (data) on public.basvuru to anon;

-- profiller: herkes kendini görür; yönetim görür ve siler; yazma yalnızca hesap işlevi
create policy p_oku on public.profiles for select to authenticated using (user_id=(select auth.uid()) or ozel.yonetici());
create policy p_sil on public.profiles for delete to authenticated using (ozel.admin() or (ozel.yonetici() and rol not in ('admin','kurum')));

create policy k_oku on public.kurumlar for select to authenticated using (ozel.admin() or (ozel.rol()='kurum' and ad=ozel.ad()));
create policy k_yaz on public.kurumlar for all to authenticated using (ozel.admin()) with check (ozel.admin());

create policy h_oku on public.hocalar for select to authenticated using (ozel.yonetici() or (ozel.rol()='ogretmen' and ad=ozel.ad()));
create policy h_yaz on public.hocalar for all to authenticated using (ozel.yonetici()) with check (ozel.yonetici());

create policy v_oku on public.veliler for select to authenticated using (ozel.yonetici() or (ozel.rol()='veli' and ad=ozel.ad()));
create policy v_yaz on public.veliler for all to authenticated using (ozel.yonetici()) with check (ozel.yonetici());

create policy o_oku on public.ogrenciler for select to authenticated using (ozel.yonetici() or ad in (select ozel.cocuklar()) or ozel.hoca_ogrencisi(ad));
create policy o_yaz on public.ogrenciler for all to authenticated using (ozel.yonetici()) with check (ozel.yonetici());

create policy z_oku on public.ogrenci_ozel for select to authenticated using (ozel.yonetici() or ad in (select ozel.cocuklar()));
create policy z_yaz on public.ogrenci_ozel for all to authenticated using (ozel.yonetici()) with check (ozel.yonetici());

create policy d_acik on public.dersler for select to anon, authenticated using (true);
create policy d_ekle on public.dersler for insert to authenticated with check (ozel.yonetici());
create policy d_guncelle on public.dersler for update to authenticated using (ozel.yonetici() or (ozel.rol()='ogretmen' and hoca=ozel.ad())) with check (ozel.yonetici() or (ozel.rol()='ogretmen' and hoca=ozel.ad()));
create policy d_sil on public.dersler for delete to authenticated using (ozel.admin());
-- öğretmen yalnızca kazanım ve planı değiştirebilir
create function ozel.ders_koru() returns trigger language plpgsql set search_path='' as $$
begin
  if ozel.rol()='ogretmen' then
    new.id:=old.id; new.hoca:=old.hoca; new.sira:=old.sira;
    new.data:=old.data || jsonb_build_object('kaz', new.data->'kaz', 'plan', new.data->'plan');
  end if;
  return new;
end $$;
create trigger ders_koru before update on public.dersler for each row execute function ozel.ders_koru();

create policy ic_oku on public.ders_ic for select to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders));
create policy ic_yaz on public.ders_ic for all to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders)) with check (ozel.yonetici() or ozel.hoca_dersi(ders));

create policy y_oku on public.yoklama for select to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders) or ogrenci in (select ozel.cocuklar()));
create policy y_yaz on public.yoklama for all to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders)) with check (ozel.yonetici() or ozel.hoca_dersi(ders));

create policy n_oku on public.ders_notu for select to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders) or ozel.uye_dersi(ders));
create policy n_yaz on public.ders_notu for all to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders)) with check (ozel.yonetici() or ozel.hoca_dersi(ders));

create policy od_oku on public.odevler for select to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders) or (ozel.uye_dersi(ders) and (hedef is null or hedef && array(select ozel.cocuklar()))));
create policy od_yaz on public.odevler for all to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders)) with check (ozel.yonetici() or ozel.hoca_dersi(ders));

create policy t_oku on public.teslimler for select to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ozel.odev_dersi(odev)) or ogrenci in (select ozel.cocuklar()));
create policy t_ekle on public.teslimler for insert to authenticated with check (ozel.yonetici() or (ozel.rol()='ogrenci' and ogrenci=ozel.ad() and ozel.odev_hedefi(odev,ogrenci)));
create policy t_guncelle on public.teslimler for update to authenticated using (ozel.yonetici() or (ozel.rol()='ogrenci' and ogrenci=ozel.ad())) with check (ozel.yonetici() or (ozel.rol()='ogrenci' and ogrenci=ozel.ad() and ozel.odev_hedefi(odev,ogrenci)));
create policy t_sil on public.teslimler for delete to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ozel.odev_dersi(odev)));

create policy g_oku on public.degerlendirmeler for select to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ozel.odev_dersi(odev)) or ogrenci in (select ozel.cocuklar()));
create policy g_yaz on public.degerlendirmeler for all to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ozel.odev_dersi(odev))) with check (ozel.yonetici() or ozel.hoca_dersi(ozel.odev_dersi(odev)));

create policy r_oku on public.kayitlar for select to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders) or (ozel.uye_dersi(ders) and (data->>'erisim'='herkes' or exists(select 1 from public.yoklama y where y.ders=kayitlar.ders and y.hafta=kayitlar.hafta and y.ogrenci in (select ozel.cocuklar()) and y.durum in ('yok','mazeret','erken')))));
create policy r_yaz on public.kayitlar for all to authenticated using (ozel.yonetici() or ozel.hoca_dersi(ders)) with check (ozel.yonetici() or ozel.hoca_dersi(ders));

-- rıza: yalnızca veli verir veya geri çeker
create policy rz_oku on public.riza for select to authenticated using (ozel.yonetici() or ogrenci in (select ozel.cocuklar()) or ozel.hoca_ogrencisi(ogrenci));
create policy rz_ekle on public.riza for insert to authenticated with check (ozel.rol()='veli' and ogrenci in (select ozel.cocuklar()));
create policy rz_guncelle on public.riza for update to authenticated using (ozel.rol()='veli' and ogrenci in (select ozel.cocuklar())) with check (ozel.rol()='veli' and ogrenci in (select ozel.cocuklar()));
create policy rz_sil on public.riza for delete to authenticated using (ozel.yonetici());

create policy om_oku on public.odemeler for select to authenticated using (ozel.admin() or (ozel.rol()='veli' and ogrenci in (select ozel.cocuklar())));
create policy om_yaz on public.odemeler for all to authenticated using (ozel.admin()) with check (ozel.admin());

create policy b_ekle on public.basvuru for insert to anon, authenticated with check (true);
create policy b_oku on public.basvuru for select to authenticated using (ozel.admin());
create policy b_sil on public.basvuru for delete to authenticated using (ozel.admin());
